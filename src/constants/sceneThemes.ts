export function getSceneTheme(stageId: string): SceneTheme {
  return SCENE_THEMES[stageId] || DEFAULT_SCENE_THEME;
}

/** 多階段魔王第 N 階段（0 起算）的場景 key：`boss-x:p2`；沒定義就沿用原場景 */
export function bossSceneId(stageId: string, phase: number): string {
  const key = `${stageId}:p${phase + 1}`;
  return phase > 0 && SCENE_THEMES[key] ? key : stageId;
}

/** 魔王目前階段的外觀；沒有分階段外觀就用 BOSS_EMOJI */
export function bossEmojiFor(stageId: string, phase: number): string {
  return BOSS_PHASE_EMOJI[stageId]?.[phase] ?? BOSS_EMOJI[stageId] ?? "👾";
}
